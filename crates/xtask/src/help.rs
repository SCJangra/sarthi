//! The help file, `:help sarthi`, as Markdown for pandoc's vimdoc writer: the prose in `crates/rpc/src/sarthi/doc/`,
//! and the settings and the API from their schemas. Each heading's id is its help tag, e.g. `sarthi-shadow.blur`, and a
//! link to `#tag` becomes `|tag|` (`links.lua`).

use std::fmt::Write;
use std::path::Path;

use rpc::sarthi::{Request, Settings, WindowConfig, WindowOptions};
use serde_json::Value;

use crate::schema::{self, Schema};

/// The help file as Markdown
pub fn markdown(root: &Path) -> String {
	let prose = |name: &str| {
		let path = root.join("crates/rpc/src/sarthi/doc").join(name);
		std::fs::read_to_string(&path).unwrap_or_else(|error| panic!("reading {}: {error}", path.display()))
	};
	let settings = Schema::of::<Settings>();
	let options = Schema::of::<WindowOptions>();
	let api = Schema::of::<Request>();
	let config = Schema::of::<WindowConfig>();

	let mut out = String::new();
	out.push_str(
		"Generated by `cargo xtask docs` from the docs of crates/rpc/src/sarthi. Edit those, not this file.\n\n",
	);
	section(&mut out, 1, "Introduction", "sarthi-intro", &prose("intro.md"));

	section(&mut out, 1, "Settings", "sarthi-settings", &prose("settings.md"));
	section(&mut out, 2, "Per-window settings", "sarthi-w:sarthi", &prose("window-options.md"));
	for (name, property) in schema::properties(&settings.root) {
		settings_section(&mut out, &settings, &options, name, settings.resolve(property), 2);
	}
	animations(&mut out, &settings);
	for (name, title, prefix) in [
		("CursorOverride", "Cursor animation overrides", "cursor_animation.overrides[n]"),
		("ScrollOverride", "Scroll animation overrides", "window.scroll_animation.overrides[n]"),
	] {
		table(&mut out, &settings, &format!("sarthi.{name}"), title, settings.def(name), prefix);
	}

	section(&mut out, 1, "Lua module", "sarthi", &prose("lua.md"));
	functions(&mut out, &api, |lua| !lua.starts_with("api."));

	section(&mut out, 1, "Window functions", "sarthi.api", &prose("api.md"));
	functions(&mut out, &api, |lua| lua.starts_with("api."));
	table(&mut out, &config, "sarthi.WindowConfig", "The `sarthi` table", &config.root, "sarthi");
	for name in ["WindowPlace", "Font"] {
		let key = if name == "WindowPlace" { "place" } else { "font" };
		table(&mut out, &config, &format!("sarthi.{name}"), &format!("sarthi.{key}"), config.def(name), key);
	}
	out
}

/// A heading at `level`, `title` with help tag `tag`, then `body`
fn section(out: &mut String, level: usize, title: &str, tag: &str, body: &str) {
	let _ = writeln!(out, "{} {title} {{#{tag}}}\n", "#".repeat(level));
	if !body.trim().is_empty() {
		let _ = writeln!(out, "{}\n", body.trim_end());
	}
}

/// Settings section `path`, e.g. `window.shadow`, with heading `level`: its keys, and the sections in it. The keys of
/// `window`'s sections can be a window's own too, in its `w:sarthi` (`options`).
fn settings_section(out: &mut String, settings: &Schema, options: &Schema, path: &str, schema: &Value, level: usize) {
	section(out, level, path, &format!("sarthi-{path}"), &schema::doc(schema));
	let window = path
		.strip_prefix("window.")
		.map(|name| window_keys(options, name))
		.unwrap_or_default();
	for (key, key_schema) in schema::properties(schema) {
		let (key_path, resolved) = (format!("{path}.{key}"), settings.resolve(key_schema));
		if resolved.get("properties").is_some() {
			settings_section(out, settings, options, &key_path, resolved, level + 1);
			continue;
		}
		let scope = if window.contains(&key) { "global, or per window" } else { "global only" };
		let default = key_schema.get("default").map(schema::lua_value);
		key_entry(out, &key_path, &format!("sarthi-{key_path}"), key_schema, default, scope);
	}
}

/// A key of a table: its name and tag, its Lua type, its default if it has one, and `note`, then its doc
fn key_entry(out: &mut String, name: &str, tag: &str, schema: &Value, default: Option<String>, note: &str) {
	let _ = writeln!(out, "#### {name} {{#{tag}}}\n");
	let mut line = format!("`{}`", schema::lua_type(schema));
	if let Some(default) = default {
		let _ = write!(line, ", default `{default}`");
	}
	if !note.is_empty() {
		let _ = write!(line, " · {note}");
	}
	let _ = writeln!(out, "{line}\n\n{}\n", schema::doc(schema));
}

/// The keys of settings section `name` that a window can have its own values of, in its `w:sarthi`
fn window_keys<'a>(options: &'a Schema, name: &str) -> Vec<&'a str> {
	let Some((_, section)) = schema::properties(&options.root)
		.into_iter()
		.find(|(section, _)| *section == name)
	else {
		return Vec::new();
	};
	schema::properties(options.resolve(section))
		.into_iter()
		.map(|(key, _)| key)
		.collect()
}

/// The curves an animation can have: each with its keys, their types and defaults
fn animations(out: &mut String, settings: &Schema) {
	let animation = settings.def("Animation");
	section(out, 2, "Animations", "sarthi.Animation", &schema::doc(animation));
	for curve in animation.get("oneOf").and_then(Value::as_array).into_iter().flatten() {
		let properties = schema::properties(curve);
		let name = properties
			.iter()
			.find(|(key, _)| *key == "type")
			.and_then(|(_, schema)| schema.get("const"))
			.and_then(Value::as_str)
			.unwrap_or_default();
		let _ = writeln!(out, "#### type = \"{name}\" {{#sarthi.Animation.{name}}}\n\n{}\n", schema::doc(curve));
		for (key, schema) in properties.into_iter().filter(|(key, _)| *key != "type") {
			let default = schema.get("default").map(schema::lua_value);
			let default =
				default.map_or_else(|| String::from(", required"), |default| format!(", default `{default}`"));
			let _ = writeln!(out, "- `{key}`: `{}`{default}. {}", schema::lua_type(schema), schema::doc(schema));
		}
		out.push('\n');
	}
}

/// The functions of the API whose Lua names `which` takes, e.g. those of `require('sarthi').api`
fn functions(out: &mut String, api: &Schema, which: impl Fn(&str) -> bool) {
	for function in api_functions(api).into_iter().filter(|function| which(&function.lua)) {
		let params: Vec<String> = function.params.iter().map(|param| format!("{{{}}}", param.name)).collect();
		let path = format!("sarthi.{}", function.lua);
		let _ = writeln!(out, "#### {path}({}) {{#{path}}}\n\n{}\n", params.join(", "), function.doc);
		if !function.params.is_empty() {
			out.push_str("Parameters:\n\n");
			for param in &function.params {
				let optional = if param.optional { "?" } else { "" };
				let _ = writeln!(out, "- `{{{}}}` (`{}{optional}`): {}", param.name, param.lua_type, param.doc);
			}
			out.push('\n');
		}
		if let Some(returns) = &function.returns {
			let _ = writeln!(out, "Returns: `{returns}`\n");
		}
	}
}

/// A table's keys, under a heading `title` with tag `tag`, from object `schema`; each key's tag is `prefix.key`
fn table(out: &mut String, schemas: &Schema, tag: &str, title: &str, schema: &Value, prefix: &str) {
	let schema = schemas.resolve(schema);
	section(out, 2, title, tag, &schema::doc(schema));
	for (key, key_schema) in schema::properties(schema) {
		key_entry(out, &format!("{prefix}.{key}"), &format!("{tag}.{key}"), key_schema, None, "");
	}
}

/// A function of the API, from its request's schema
pub struct Function {
	/// Its Lua name in `require('sarthi')`, e.g. `api.nvim_open_win`
	pub lua: String,

	/// The request's name, e.g. `nvim_open_win`
	pub method: String,
	pub doc: String,
	pub params: Vec<Param>,

	/// Its Lua return type, if it returns something
	pub returns: Option<String>,
}

/// A parameter of a [`Function`]
pub struct Param {
	pub name: String,
	pub lua_type: String,
	pub optional: bool,
	pub doc: String,
}

/// The functions of the API: the requests with a Lua name (`x-lua`), in order
pub fn api_functions(api: &Schema) -> Vec<Function> {
	let requests = api.root.get("oneOf").and_then(Value::as_array).cloned().unwrap_or_default();
	requests
		.iter()
		.filter_map(|request| {
			let lua = request.get("x-lua")?.as_str()?.to_owned();
			let (method, args) = schema::properties(request).into_iter().next()?;
			let args = api.resolve(args);
			let params = schema::properties(args)
				.into_iter()
				.map(|(name, schema)| Param {
					name: name.to_owned(),
					lua_type: schema::lua_type(schema),
					optional: !schema::required(args, name),
					doc: schema::doc(schema),
				})
				.collect();
			Some(Function {
				lua,
				method: method.to_owned(),
				doc: schema::doc(request),
				params,
				returns: request.get("x-returns").and_then(Value::as_str).map(str::to_owned),
			})
		})
		.collect()
}
